export type DocsSection = 'docs' | 'blog';
export type DocsLocale = 'en' | 'es';

export type DocsPage = {
  title: string;
  description: string;
  keywords: string[];
  sidebarLabel?: string;
  section: DocsSection;
  locale: DocsLocale;
  path: string;
  url: string;
  source: string;
  content: string;
};

export type DocsIndex = {
  generatedAt: string;
  siteUrl: string;
  pages: DocsPage[];
};

const CACHE_TTL_MS = 60 * 60 * 1000;

const FETCH_TIMEOUT_MS = 10_000;

let cache: {index: DocsIndex; fetchedAt: number} | null = null;
let inflight: Promise<DocsIndex> | null = null;

export class DocsIndexUnavailableError extends Error {}

export function parseDocsIndex(raw: unknown): DocsIndex {
  const data = raw as Partial<DocsIndex> | null;
  if (!data || !Array.isArray(data.pages)) {
    throw new Error('docs index JSON has no pages array');
  }
  return {
    generatedAt: typeof data.generatedAt === 'string' ? data.generatedAt : '',
    siteUrl: typeof data.siteUrl === 'string' ? data.siteUrl : '',
    pages: data.pages
      .filter((page) => page && typeof page.path === 'string')
      .map((page) => ({
        ...page,
        title: typeof page.title === 'string' && page.title ? page.title : page.path,
        description: typeof page.description === 'string' ? page.description : '',
        keywords: Array.isArray(page.keywords) ? page.keywords : [],
        content: typeof page.content === 'string' ? page.content : '',
      })),
  };
}

export function resetDocsIndexCache(): void {
  cache = null;
  inflight = null;
}

async function fetchDocsIndex(url: string, fetcher: typeof fetch): Promise<DocsIndex> {
  const now = Date.now();
  try {
    const response =
      fetcher === fetch
        ? await fetcher(url, {
            signal: AbortSignal.timeout(FETCH_TIMEOUT_MS),
            cf: {cacheTtl: 3600, cacheEverything: true},
          } as RequestInit)
        : await fetcher(url);
    if (!response.ok) {
      throw new Error(`HTTP ${response.status}`);
    }
    const index = parseDocsIndex(await response.json());
    cache = {index, fetchedAt: now};
    return index;
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    if (cache) {
      console.warn(`[docs-mcp] refresh of ${url} failed (${reason}); serving cached index from ${new Date(cache.fetchedAt).toISOString()}`);
      return cache.index;
    }
    throw new DocsIndexUnavailableError(
      `The plugNmeet docs index could not be loaded from ${url} (${reason}). ` +
        'The documentation site may not have deployed docs-index.json yet — it is generated by the docs-index plugin at build time.',
    );
  }
}

export async function loadDocsIndex(url: string, fetcher: typeof fetch = fetch): Promise<DocsIndex> {
  if (cache && Date.now() - cache.fetchedAt < CACHE_TTL_MS) {
    return cache.index;
  }
  inflight ??= fetchDocsIndex(url, fetcher).finally(() => {
    inflight = null;
  });
  return inflight;
}
